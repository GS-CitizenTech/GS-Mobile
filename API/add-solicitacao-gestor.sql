-- SOLICITACOES DE ACESSO AO PERFIL GESTOR
-- Execute no mesmo schema Oracle utilizado pela API Alerta Cidadao.
-- O script pode ser executado novamente sem recriar a tabela ou os indices.
-- ============================================================================

DECLARE
    V_COUNT INTEGER;
BEGIN
    SELECT COUNT(*) INTO V_COUNT
      FROM USER_TABLES
     WHERE TABLE_NAME = 'SOLICITACAO_GESTOR';

    IF V_COUNT = 0 THEN
        EXECUTE IMMEDIATE '
            CREATE TABLE "SOLICITACAO_GESTOR" (
                "ID_SOLICITACAO_GESTOR" NUMBER(20,0) GENERATED BY DEFAULT ON NULL AS IDENTITY NOT NULL,
                "ID_USUARIO" NUMBER(20,0) NOT NULL,
                "MOTIVO" NVARCHAR2(500) NOT NULL,
                "STATUS" NVARCHAR2(20) DEFAULT N''PENDENTE'' NOT NULL,
                "DATA_SOLICITACAO" TIMESTAMP WITH TIME ZONE DEFAULT SYSTIMESTAMP NOT NULL,
                "DATA_DECISAO" TIMESTAMP WITH TIME ZONE NULL,
                "ID_GESTOR_RESPONSAVEL" NUMBER(20,0) NULL,
                "OBSERVACAO_DECISAO" NVARCHAR2(500) NULL,
                CONSTRAINT "PK_SOLICITACAO_GESTOR" PRIMARY KEY ("ID_SOLICITACAO_GESTOR"),
                CONSTRAINT "FK_SOL_GESTOR_USUARIO" FOREIGN KEY ("ID_USUARIO") REFERENCES "USUARIO" ("ID_USUARIO"),
                CONSTRAINT "FK_SOL_GESTOR_RESPONSAVEL" FOREIGN KEY ("ID_GESTOR_RESPONSAVEL") REFERENCES "USUARIO" ("ID_USUARIO"),
                CONSTRAINT "CK_SOL_GESTOR_STATUS" CHECK ("STATUS" IN (''PENDENTE'', ''APROVADA'', ''REJEITADA''))
            )';
        DBMS_OUTPUT.PUT_LINE('Tabela SOLICITACAO_GESTOR criada.');
    ELSE
        DBMS_OUTPUT.PUT_LINE('Tabela SOLICITACAO_GESTOR ja existe; estrutura preservada.');
    END IF;

    SELECT COUNT(*) INTO V_COUNT FROM USER_INDEXES WHERE INDEX_NAME = 'IX_SOL_GESTOR_USUARIO_STATUS';
    IF V_COUNT = 0 THEN
        EXECUTE IMMEDIATE 'CREATE INDEX "IX_SOL_GESTOR_USUARIO_STATUS" ON "SOLICITACAO_GESTOR" ("ID_USUARIO", "STATUS")';
    END IF;

    SELECT COUNT(*) INTO V_COUNT FROM USER_INDEXES WHERE INDEX_NAME = 'IX_SOL_GESTOR_STATUS_DATA';
    IF V_COUNT = 0 THEN
        EXECUTE IMMEDIATE 'CREATE INDEX "IX_SOL_GESTOR_STATUS_DATA" ON "SOLICITACAO_GESTOR" ("STATUS", "DATA_SOLICITACAO")';
    END IF;

    SELECT COUNT(*) INTO V_COUNT FROM USER_INDEXES WHERE INDEX_NAME = 'UQ_SOL_GESTOR_PENDENTE';
    IF V_COUNT = 0 THEN
        EXECUTE IMMEDIATE 'CREATE UNIQUE INDEX "UQ_SOL_GESTOR_PENDENTE" ON "SOLICITACAO_GESTOR" (CASE WHEN "STATUS" = ''PENDENTE'' THEN "ID_USUARIO" ELSE NULL END)';
    END IF;
END;
/

